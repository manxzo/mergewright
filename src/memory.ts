// Project memory: a small always-loaded core and on-demand files, changed only through these functions.
//
//   memory/STATE.md            always loaded; where the project is now          (capped)
//   memory/RULES.md            always loaded; standing rules, owner-controlled  (capped)
//   memory/INDEX.md            always loaded; generated, one line per file below
//   memory/lessons/<topic>.md  on demand; one "## Title" entry per lesson
//   memory/decisions/<date>-<slug>.md
//   memory/outcomes/<CARD>.md
import fs from "node:fs";
import path from "node:path";
import type { Project } from "./project.ts";
import { listFiles, MwError, readIfExists, readText, redactSecrets, slugify, today, writeAllAtomic } from "./util.ts";

export interface Lesson {
  topic: string;
  title: string;
  body: string;
  card?: string;
}

export interface Reflection {
  state: string;
  outcome: string;
  lessons: { topic: string; title: string; body: string }[];
  decisions: { title: string; body: string }[];
}

const INDEX_HEADER = "# Index\n\n<!-- Generated by `mw memory index` from the files in memory/. Do not edit. -->\n";

/**
 * New contents of memory files by absolute path, computed but not yet written. Planning reads through
 * it, so two lessons on one topic stack and the index lists files about to be created.
 */
type Planned = Map<string, string>;

const readPlanned = (planned: Planned, file: string): string | undefined => planned.get(file) ?? readIfExists(file);

/** `.md` files directly in `dir`, on disk or planned, sorted. */
function mdFiles(dir: string, planned: Planned): string[] {
  const planHere = [...planned.keys()].filter((f) => path.dirname(f) === dir && f.endsWith(".md"));
  return [...new Set([...listFiles(dir, ".md"), ...planHere])].sort((a, b) => (path.basename(a) < path.basename(b) ? -1 : path.basename(a) > path.basename(b) ? 1 : 0));
}

/** One `## Title` entry of a markdown file. */
interface Entry {
  title: string;
  body: string;
}

/**
 * The `## Title` entries of a file, in order. Headings inside code fences are text, not entries,
 * and two entries with the same title stay two entries (nothing is merged or dropped on read).
 */
function entries(text: string): Entry[] {
  const out: Entry[] = [];
  let cur: { title: string; buf: string[] } | undefined;
  let inFence = false;
  const flush = () => { if (cur) out.push({ title: cur.title, body: cur.buf.join("\n").trim() }); };
  for (const line of text.split(/\r?\n/)) {
    if (/^(```|~~~)/.test(line.trim())) inFence = !inFence;
    const m = !inFence && /^##[ \t]+(.+?)[ \t]*$/.exec(line);
    if (m) { flush(); cur = { title: m[1]!, buf: [] }; } else cur?.buf.push(line);
  }
  flush();
  return out;
}

function firstHeading(text: string): string {
  return /^#[ \t]+(.+)$/m.exec(text)?.[1]?.trim() ?? "";
}

/** The index text for the project's current memory files (plus `planned` ones). Deterministic, so `check` can compare it. */
export function renderIndex(project: Project, planned: Planned = new Map()): string {
  const mem = project.abs("memory");
  const text = (f: string) => readPlanned(planned, f) ?? "";
  const lines = [INDEX_HEADER, "## Lessons"];
  for (const f of mdFiles(path.join(mem, "lessons"), planned)) {
    if (path.basename(f) === "README.md") continue;
    const titles = entries(text(f)).map((e) => e.title);
    if (titles.length) lines.push(`- lessons/${path.basename(f)}: ${titles.join("; ")}`);
  }
  lines.push("", "## Decisions");
  for (const f of mdFiles(path.join(mem, "decisions"), planned)) {
    if (path.basename(f) === "README.md") continue;
    lines.push(`- decisions/${path.basename(f)}: ${firstHeading(text(f))}`);
  }
  lines.push("", "## Outcomes");
  for (const f of mdFiles(path.join(mem, "outcomes"), planned)) {
    if (path.basename(f) === "README.md") continue;
    lines.push(`- outcomes/${path.basename(f)}: ${firstHeading(text(f)).replace(/^\S+\s*/, "") || "(no title)"}`);
  }
  return lines.join("\n") + "\n";
}

/** Plan the index; false when it would not change. */
function planIndex(project: Project, planned: Planned): boolean {
  const next = renderIndex(project, planned);
  if (readIfExists(project.memoryFile("INDEX.md")) === next) return false;
  planned.set(project.memoryFile("INDEX.md"), next);
  return true;
}

function writePlanned(planned: Planned): void {
  writeAllAtomic([...planned].map(([file, content]) => ({ file, content })));
}

export function writeIndex(project: Project): boolean {
  const planned: Planned = new Map();
  if (!planIndex(project, planned)) return false;
  writePlanned(planned);
  return true;
}

/** Lines of a file, ignoring trailing blank lines. The caps on STATE.md and RULES.md use this. */
export function lineCount(text: string): number {
  return text.replace(/\n+$/, "").split("\n").length;
}

/** Plan STATE.md. Refuses text over the cap: the file is in every prompt, so its size is a budget. */
function planState(project: Project, text: string, planned: Planned): void {
  const body = text.trim() + "\n";
  const cap = project.config.memory.stateMaxLines;
  if (lineCount(body) > cap) throw new MwError("memory/too-long", `the new state is ${lineCount(body)} lines; the cap is ${cap}. Shorten it: state says where the project is now, not its history`);
  if (!/^#[ \t]+\S/m.test(body)) throw new MwError("memory/state-form", "the state must start with a '# ' heading");
  planned.set(project.memoryFile("STATE.md"), body);
}

/** Replace STATE.md (see planState for what is refused). */
export function setState(project: Project, text: string): void {
  const planned: Planned = new Map();
  planState(project, text, planned);
  writePlanned(planned);
}

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();

/** Plan a lesson in its topic file. A lesson with the same title replaces the old entry instead of piling up. */
function planLesson(project: Project, lesson: Lesson, planned: Planned): { file: string; result: "added" | "updated" } {
  const topic = slugify(lesson.topic);
  const title = lesson.title.trim().replace(/\s+/g, " ");
  if (!title || !lesson.body.trim()) throw new MwError("memory/lesson-form", "a lesson needs a title and a body");
  const file = project.abs(path.join("memory", "lessons", `${topic}.md`));
  const existing = readPlanned(planned, file);
  const list = existing ? entries(existing) : [];
  const heading = existing ? firstHeading(existing) : "";
  const meta = [`- added: ${today()}`];
  if (lesson.card) meta.push(`- card: ${lesson.card}`);
  const block = `${lesson.body.trim()}\n\n${meta.join("\n")}`;
  // Replace the first entry with this title in place; other entries are written back untouched.
  const dup = list.findIndex((e) => norm(e.title) === norm(title));
  if (dup >= 0) list[dup] = { title, body: block };
  else list.push({ title, body: block });
  const out = [`# ${heading || topic.replace(/-/g, " ").replace(/^./, (c) => c.toUpperCase())}`, ""];
  for (const e of list) out.push(`## ${e.title}`, "", e.body, "");
  planned.set(file, out.join("\n"));
  return { file: `memory/lessons/${topic}.md`, result: dup >= 0 ? "updated" : "added" };
}

/** Add a lesson to its topic file. A lesson with the same title replaces the old entry instead of piling up. */
export function addLesson(project: Project, lesson: Lesson): "added" | "updated" {
  const planned: Planned = new Map();
  const r = planLesson(project, lesson, planned);
  writePlanned(planned);
  return r.result;
}

/** Plan a decision file; returns its project-relative path. */
function planDecision(project: Project, decision: { title: string; body: string; card?: string }, planned: Planned): string {
  const title = decision.title.trim().replace(/\s+/g, " ");
  if (!title || !decision.body.trim()) throw new MwError("memory/decision-form", "a decision needs a title and a body");
  const dir = project.abs(path.join("memory", "decisions"));
  // The same decision recorded again for the same card (a repeated reflect phase) replaces its file.
  const same = decision.card
    ? mdFiles(dir, planned).find((f) => { const t = readPlanned(planned, f) ?? ""; return firstHeading(t) === title && t.includes(`- card: ${decision.card}\n`); })
    : undefined;
  const taken = (name: string) => planned.has(path.join(dir, name)) || fs.existsSync(path.join(dir, name));
  let name = same ? path.basename(same) : `${today()}-${slugify(title)}.md`;
  for (let n = 2; !same && taken(name); n++) name = `${today()}-${slugify(title)}-${n}.md`;
  const meta = [`- date: ${today()}`];
  if (decision.card) meta.push(`- card: ${decision.card}`);
  planned.set(path.join(dir, name), `# ${title}\n\n${meta.join("\n")}\n\n${decision.body.trim()}\n`);
  return `memory/decisions/${name}`;
}

export function addDecision(project: Project, decision: { title: string; body: string; card?: string }): string {
  const planned: Planned = new Map();
  const rel = planDecision(project, decision, planned);
  writePlanned(planned);
  return rel;
}

function planOutcome(project: Project, cardId: string, title: string, text: string, planned: Planned): void {
  if (!text.trim()) throw new MwError("memory/outcome-form", "an outcome needs text");
  planned.set(project.abs(path.join("memory", "outcomes", `${cardId}.md`)), `# ${cardId} ${title}\n\n- finished: ${today()}\n\n${text.trim()}\n`);
}

export function setOutcome(project: Project, cardId: string, title: string, text: string): void {
  const planned: Planned = new Map();
  planOutcome(project, cardId, title, text, planned);
  writePlanned(planned);
}

export interface ReflectionResult {
  lessons: { title: string; topic: string; result: "added" | "updated" }[];
  decisions: string[];
  /** Project-relative paths the reflection wrote (memory/INDEX.md only when it changed). */
  files: string[];
}

export interface ApplyOptions {
  /** Leave STATE.md as it is and apply everything else. */
  skipState?: boolean;
  /**
   * Called once every new content is computed and before the first file is written; throwing stops
   * the apply with nothing written. The engine re-checks there that memory/ has no uncommitted edits.
   */
  guard?: () => void;
}

/**
 * Apply a reflect phase's output: new state, the card's outcome, lessons and decisions, then the index.
 * Everything is computed first (a refusal, such as a state over its cap, changes nothing), then
 * `opts.guard` runs, then all files are written in one step (`writeAllAtomic`).
 */
export function applyReflection(project: Project, cardId: string, cardTitle: string, raw: Reflection, opts: ApplyOptions = {}): ReflectionResult {
  // Memory is committed and loaded into prompts: a credential a model happened to see never goes in.
  const r: Reflection = {
    state: redactSecrets(raw.state),
    outcome: redactSecrets(raw.outcome),
    lessons: raw.lessons.map((l) => ({ ...l, title: redactSecrets(l.title), body: redactSecrets(l.body) })),
    decisions: raw.decisions.map((d) => ({ title: redactSecrets(d.title), body: redactSecrets(d.body) })),
  };
  const planned: Planned = new Map();
  if (!opts.skipState) planState(project, r.state, planned);
  planOutcome(project, cardId, cardTitle, r.outcome, planned);
  const lessons = r.lessons.map((l) => {
    const p = planLesson(project, { ...l, card: cardId }, planned);
    return { title: l.title, topic: slugify(l.topic), result: p.result };
  });
  const decisions = r.decisions.map((d) => planDecision(project, { ...d, card: cardId }, planned));
  const files = [...(opts.skipState ? [] : ["memory/STATE.md"]), `memory/outcomes/${cardId}.md`, ...lessons.map((l) => `memory/lessons/${l.topic}.md`), ...decisions];
  if (planIndex(project, planned)) files.push("memory/INDEX.md");
  opts.guard?.();
  writePlanned(planned);
  return { lessons, decisions, files: [...new Set(files)] };
}

export interface MemoryHit {
  file: string;
  title: string;
  text: string;
  score: number;
}

const STOP = new Set(["the", "and", "for", "with", "that", "this", "from", "are", "was", "not", "but", "has", "have", "its", "into", "when", "then", "given", "should", "must", "can", "will", "all", "any", "one", "use", "add", "new"]);

export function keywords(text: string): string[] {
  return [...new Set(text.toLowerCase().split(/[^a-z0-9_]+/).filter((w) => w.length > 2 && !STOP.has(w)))];
}

/** Something a keyword search may return: `match` is the text scored (default `text`). */
export interface SearchCandidate {
  file: string;
  title: string;
  text: string;
  match?: string;
}

/**
 * The keyword ranking `mw memory search` and `mw docs search` share: the query's words of three or
 * more characters (common words dropped) score 3 each when in the title and 1 each when in the text.
 * Candidates that score nothing are dropped; the best `limit` are returned, ties by file.
 */
export function rankByKeywords(query: string, candidates: Iterable<SearchCandidate>, limit: number): MemoryHit[] {
  const words = keywords(query);
  if (!words.length) return [];
  const hits: MemoryHit[] = [];
  for (const c of candidates) {
    const t = c.title.toLowerCase();
    const b = (c.match ?? c.text).toLowerCase();
    let s = 0;
    for (const w of words) {
      if (t.includes(w)) s += 3;
      if (b.includes(w)) s += 1;
    }
    if (s > 0) hits.push({ file: c.file, title: c.title, text: c.text, score: s });
  }
  return hits.sort((a, b) => b.score - a.score || a.file.localeCompare(b.file)).slice(0, limit);
}

/** Keyword search over lessons, decisions and outcomes. Good enough to pick the few entries worth loading. */
export function searchMemory(project: Project, query: string, limit = 5): MemoryHit[] {
  if (!keywords(query).length) return [];
  const mem = project.abs("memory");
  const candidates: SearchCandidate[] = [];
  for (const f of listFiles(path.join(mem, "lessons"), ".md")) {
    if (path.basename(f) === "README.md") continue;
    for (const { title, body: text } of entries(readText(f))) candidates.push({ file: `memory/lessons/${path.basename(f)}`, title, text });
  }
  for (const dir of ["decisions", "outcomes"]) {
    for (const f of listFiles(path.join(mem, dir), ".md")) {
      if (path.basename(f) === "README.md") continue;
      const text = readText(f);
      candidates.push({ file: `memory/${dir}/${path.basename(f)}`, title: firstHeading(text), text: text.replace(/^#.*\n+/, "").trim(), match: text });
    }
  }
  return rankByKeywords(query, candidates, limit);
}

/** Lessons as plain records (for mirroring into mem0 and for tests). */
export function allLessons(project: Project): Lesson[] {
  const out: Lesson[] = [];
  for (const f of listFiles(project.abs(path.join("memory", "lessons")), ".md")) {
    if (path.basename(f) === "README.md") continue;
    const topic = path.basename(f, ".md");
    for (const { title, body } of entries(readText(f))) out.push({ topic, title, body });
  }
  return out;
}

/** A lesson or decision as the semantic stores get it: the text without the file's own `- added:` / `- date:` / `- card:` lines. */
export interface MemoryRecord {
  topic: string;
  title: string;
  body: string;
  card?: string;
}

/** Split the trailing (lessons) or leading (decisions) metadata list off an entry body. */
function splitMeta(text: string, where: "head" | "tail"): { body: string; card?: string } {
  const lines = text.trim().split("\n");
  const meta = /^- (added|date|card): (.*)$/;
  let card: string | undefined;
  if (where === "tail") {
    let i = lines.length;
    while (i > 0 && meta.test(lines[i - 1]!)) i--;
    if (i === lines.length || (i > 0 && lines[i - 1]!.trim() !== "")) return { body: text.trim() };
    for (const l of lines.slice(i)) { const m = meta.exec(l)!; if (m[1] === "card") card = m[2]!.trim(); }
    return { body: lines.slice(0, i).join("\n").trim(), card };
  }
  let i = 0;
  while (i < lines.length && meta.test(lines[i]!)) { const m = meta.exec(lines[i]!)!; if (m[1] === "card") card = m[2]!.trim(); i++; }
  return { body: lines.slice(i).join("\n").trim(), card };
}

/** Every lesson in memory/lessons/ as a record (topic = file name), in file order. */
export function lessonRecords(project: Project): MemoryRecord[] {
  const out: MemoryRecord[] = [];
  for (const f of listFiles(project.abs(path.join("memory", "lessons")), ".md")) {
    if (path.basename(f) === "README.md") continue;
    const topic = path.basename(f, ".md");
    for (const e of entries(readText(f))) {
      const { body, card } = splitMeta(e.body, "tail");
      if (body) out.push({ topic, title: e.title, body, ...(card ? { card } : {}) });
    }
  }
  return out;
}

/** Every decision in memory/decisions/ as a record (topic `decision`, as `mw memory add decision` stores it). */
export function decisionRecords(project: Project): MemoryRecord[] {
  const out: MemoryRecord[] = [];
  for (const f of listFiles(project.abs(path.join("memory", "decisions")), ".md")) {
    if (path.basename(f) === "README.md") continue;
    const text = readText(f);
    const title = firstHeading(text);
    const { body, card } = splitMeta(text.replace(/^#[ \t]+.*\n*/m, ""), "head");
    if (title && body) out.push({ topic: "decision", title, body, ...(card ? { card } : {}) });
  }
  return out;
}
